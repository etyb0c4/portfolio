import { chromium } from 'playwright'
const b = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
const errs = []
p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()) })
p.on('pageerror', (e) => errs.push('PAGEERROR: ' + e.message))
await p.goto('http://localhost:5199/', { waitUntil: 'networkidle' })
await p.waitForTimeout(4200)
const forkTop = await p.evaluate(() => document.getElementById('fork').offsetTop)
await p.evaluate((y) => scrollTo(0, y), forkTop); await p.waitForTimeout(2400)
await p.screenshot({ path: '.shots/v6/00-fork.jpg', type: 'jpeg', quality: 78 })
await p.hover('.gate-card.dark'); await p.waitForTimeout(600)
await p.screenshot({ path: '.shots/v6/01-fork-hover.jpg', type: 'jpeg', quality: 78 })
await p.click('.gate-card.dark'); await p.waitForTimeout(2600)
await p.screenshot({ path: '.shots/v6/02-dark-record.jpg', type: 'jpeg', quality: 78 })
const ops = await p.evaluate(() => document.getElementById('ops').offsetTop)
await p.evaluate((y) => scrollTo(0, y), ops); await p.waitForTimeout(2000)
await p.screenshot({ path: '.shots/v6/03-dark-ops.jpg', type: 'jpeg', quality: 78 })
await p.click('#cross'); await p.waitForTimeout(2600)
await p.screenshot({ path: '.shots/v6/04-good-work.jpg', type: 'jpeg', quality: 78 })
const c = await p.evaluate(() => document.getElementById('contact').offsetTop)
await p.evaluate((y) => scrollTo(0, y), c); await p.waitForTimeout(2200)
await p.screenshot({ path: '.shots/v6/05-contact.jpg', type: 'jpeg', quality: 78 })
console.log(errs.length ? 'ERRORS:\n' + [...new Set(errs)].slice(0, 8).join('\n') : 'clean')
await b.close()
